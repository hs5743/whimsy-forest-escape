// Generate the server validators from the same pure modules used by the game.
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const base=path.resolve(__dirname,'..');
function generate(){
const context=vm.createContext({window:{},console});
vm.runInContext(fs.readFileSync(path.join(base,'spatial-zone-manager.js'),'utf8')+';window.Manager=SpatialZoneManager;',context);
context.window.Manager.prototype.initTextures=()=>{};
const manager=new context.window.Manager({});
const zones=Object.fromEntries(Object.entries(manager.zones).map(([id,z])=>[id,{id,words:Array.from(z.words)}]));
let output='// GENERATED by scripts/build-gas-schema.cjs. Do not edit independently.\n';
for(const file of ['realm-quests.js','adventure-progress.js']){
 const source=fs.readFileSync(path.join(base,file),'utf8'),end=source.indexOf('  if(!root.document)return;');
 if(end<0)throw Error('Pure module boundary missing: '+file);
 output+=source.slice(0,end)+'})(globalThis);\n';
}
output+='var ADVENTURE_CHECKPOINT_ZONES='+JSON.stringify(zones)+';\n';
return output;
}
if(require.main===module)fs.writeFileSync(path.join(base,'gas/AdventureSchema.gs'),generate());
module.exports=generate;
